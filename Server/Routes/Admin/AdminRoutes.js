import { Router } from "express";
import adminAuthRouter from "./adminAuthRouteHandler.js";
import {
  verifyAdmin,
  verifyToken,
  verifyTrustedRequestOrigin,
} from "../../Middlewares/AuthMiddleware.js";
import {
  addPizza,
  addProduct,
  allOrders,
  dashboard,
  deletePizza,
  deleteProduct,
  deleteUser,
  getAllUsers,
  getOrderAccStatus,
  getPizzaDetails,
  getPizzas,
  getUserCart,
  getUserWithNameOrEmail,
  imageUpload,
  inventory,
  OrderDetails,
  updateOrderStatus,
  updatePizza,
  updateProduct,
  updateUser,
  userOrders,
  orderData,
  revenueData,
} from "../../Controllers/Admin/AdminMiscController.js";
import { upload, validateUploadedImage } from "../../Services/ImageStorage.js";

const AdminRouter = Router();

// Middleware for All the auth Routes related to Admin.
AdminRouter.use("/auth", adminAuthRouter);

AdminRouter.get("/dashboard", verifyToken, verifyAdmin, dashboard);
AdminRouter.get("/dashboard/revenue", verifyToken, verifyAdmin, revenueData); // -Data for LineChart creation which denotes the revenue generated by the store in each month
AdminRouter.get("/dashboard/order", verifyToken, verifyAdmin, orderData); // -Data for PieChart creation which denotes the ration of status of orders

// Admin - Inventory Routes
AdminRouter.get("/inventory", verifyToken, verifyAdmin, inventory);
AdminRouter.post("/addproduct", verifyTrustedRequestOrigin, verifyToken, verifyAdmin, addProduct);
AdminRouter.patch("/updateproduct", verifyTrustedRequestOrigin, verifyToken, verifyAdmin, updateProduct);
AdminRouter.delete("/deleteproduct", verifyTrustedRequestOrigin, verifyToken, verifyAdmin, deleteProduct);

// Admin - pizza Routes
/**
 *  Used to upload the image of pizza Locally using multer.And Not being used in the deployed version AS Cloudinary is being used.
 */
AdminRouter.post(
  "/pizza/upload",
  verifyTrustedRequestOrigin,
  verifyToken,
  verifyAdmin,
  upload.single("image"),
  validateUploadedImage,
  imageUpload
);

AdminRouter.get("/get-pizzas", verifyToken, verifyAdmin, getPizzas);
AdminRouter.get("/pizza/get-pizza-details", verifyToken, verifyAdmin, getPizzaDetails);
AdminRouter.post("/addpizza", verifyTrustedRequestOrigin, verifyToken, verifyAdmin, addPizza);
AdminRouter.patch("/updatepizza", verifyTrustedRequestOrigin, verifyToken, verifyAdmin, updatePizza);
AdminRouter.delete("/deletepizza", verifyTrustedRequestOrigin, verifyToken, verifyAdmin, deletePizza);

// Admin - User Routes
AdminRouter.get("/users-list", verifyToken, verifyAdmin, getAllUsers);
AdminRouter.get("/user/search", verifyToken, verifyAdmin, getUserWithNameOrEmail);
AdminRouter.patch("/update-user", verifyTrustedRequestOrigin, verifyToken, verifyAdmin, updateUser);
AdminRouter.delete("/delete-user", verifyTrustedRequestOrigin, verifyToken, verifyAdmin, deleteUser);

AdminRouter.get("/user/cart",verifyToken,verifyAdmin,getUserCart)

// Admin -> User - Order Details
AdminRouter.get("/orders", verifyToken, verifyAdmin, allOrders);
AdminRouter.patch("/order", verifyTrustedRequestOrigin, verifyToken, verifyAdmin, updateOrderStatus);
AdminRouter.get("/user/orders", verifyToken, verifyAdmin, userOrders);
AdminRouter.get("/orders/filtered", verifyToken, verifyAdmin, getOrderAccStatus); // -> GET -> status : query -> orders according to given valid status like "completed" or "pending"
AdminRouter.get("/order/detail", verifyToken, verifyAdmin, OrderDetails);

export default AdminRouter;
